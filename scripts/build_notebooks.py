def main() -> None:
    out = Path("notebooks")
    out.mkdir(exist_ok=True)
    for name, cells in NB.items():
        nb = nbf.v4.new_notebook()
        nb["cells"] = cells
        nb["metadata"]["kernelspec"] = {
            "name": "python3",
            "display_name": "Python 3",
            "language": "python",
        }
        nbf.write(nb, out / name)
        print("wrote", out / name)


if __name__ == "__main__":
    main()
